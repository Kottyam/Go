const KEY = "go-lang";

function fill(template: string, a = "", b = "") {
  return template.replaceAll("{a}", a).replaceAll("{b}", b);
}

export function noticeText(lang: Lang, raw: string) {
  if (!raw.startsWith("@")) return raw;
  const [key, a = "", b = ""] = raw.slice(1).split("|");
  const table = copy[lang].n as Record<string, string>;
  const line = table[key];
  return line ? fill(line, a, b) : raw;
}

export function monthText(lang: Lang, key: string) {
  const [y, m] = key.split("-").map(Number);
  return `${copy[lang].months[(m ?? 1) - 1] ?? ""} ${y ?? ""}`;
}

export function serviceText(lang: Lang, shop: { kind: ShopKind; serviceName?: string }) {
  if (shop.kind === "custom") return shop.serviceName?.trim() || copy[lang].svc.custom;
  return copy[lang].svc[shop.kind];
}

const Ctx = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Copy } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = localStorage.getItem(KEY);
    if (saved === "ml" || saved === "ta" || saved === "kn" || saved === "te" || saved === "hi" || saved === "en") {
      setLangState(saved);
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const api = useMemo(() => {
    const setLang = (next: Lang) => {
      setLangState(next);
      localStorage.setItem(KEY, next);
    };
    return { lang, setLang, t: copy[lang] };
  }, [lang]);
  return <Ctx.Provider value={api}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}

export function LangSelect() {
  const { lang, setLang, t } = useI18n();
  return (
    <select
      aria-label={t.language}
      className="field w-auto max-w-44 min-h-11 shrink-0 bg-card px-2 text-sm"
      value={lang}
      onChange={(e) => setLang(e.target.value as Lang)}
    >
      {LANGS.map((item) => (
        <option key={item.id} value={item.id}>
          {item.name}
        </option>
      ))}
    </select>
  );
}
