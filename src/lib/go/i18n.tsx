const dicts = { en, ml };
type Ctx = { lang: Lang; t: (k: Key) => string; toggle: () => void };
const I18n = createContext<Ctx>({ lang: "en", t: (k) => en[k], toggle: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("go.lang") === "ml" ? "ml" : "en"));
  const toggle = useCallback(() => {
    setLang((l) => {
      const n = l === "en" ? "ml" : "en";
      localStorage.setItem("go.lang", n);
      return n;
    });
  }, []);
  const t = useCallback((k: Key) => dicts[lang][k] ?? en[k], [lang]);
  return <I18n.Provider value={{ lang, t, toggle }}>{children}</I18n.Provider>;
}

export const useT = () => useContext(I18n);
